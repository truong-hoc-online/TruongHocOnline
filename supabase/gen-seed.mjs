// Build supabase/seed.sql (shop_items) from the mod packs, using the game's own validatePack().
// Usage: node supabase/gen-seed.mjs
// Re-running is safe: new items are inserted; existing rows keep the price/enabled set in the admin page.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { validatePack } = await import(pathToFileURL(join(root, 'js', 'items.js')).href);

const sqlStr = (s) => `'${String(s).replace(/'/g, "''")}'`;
const index = JSON.parse(readFileSync(join(root, 'mods', 'index.json'), 'utf8'));
const rows = [];
for (const f of index.packs) {
  const { items, errors } = validatePack(JSON.parse(readFileSync(join(root, 'mods', f), 'utf8')), f);
  if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
  for (const it of items) rows.push(`  (${sqlStr(it.id)}, ${sqlStr(it.type)}, ${sqlStr(it.name)}, ${it.price})`);
}

const sql = `-- Generated by supabase/gen-seed.mjs from mods/*.json — do not edit by hand.
insert into public.shop_items (id, type, name, price) values
${rows.join(',\n')}
on conflict (id) do update set type = excluded.type, name = excluded.name;
`;
writeFileSync(join(root, 'supabase', 'seed.sql'), sql);
console.log(`seed.sql: ${rows.length} items`);
